#include <esp_log.h>
#include "stm32.h"

#include "i2c.h"

//-----------------------------------------------------------------------------
// Constants/Macros Definitions
//-----------------------------------------------------------------------------

#define SLAVE_ADDRESS          0x04u  //!< Slave address

#define WHO_AM_I_REG_ADDRESS   0x0Fu  //!< Who_AM_I register address (Read only)
#define BUTTON_REG_ADDRESS     0x00u

#define STM32_ID               0xBCu  //!< ID of the STM32

//-----------------------------------------------------------------------------
// Types Definitions
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// Exported Global Data
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// Private Data
//-----------------------------------------------------------------------------

static const char* Tag = "stm32";

//-----------------------------------------------------------------------------
// Private Functions Prototypes
//-----------------------------------------------------------------------------

//! \brief     Read the ID
//! \pre       None
//! \param     None
//! \return    None
//! \image     None
static void ReadId(uint8_t* data);

//-----------------------------------------------------------------------------
// Inline Code Definition
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// Functions Implementation
//-----------------------------------------------------------------------------

void STM32_Init(void)
{

}

//_____________________________________________________________________________

void STM32_CheckId(void)
{
  uint8_t id = 0x00;

  ReadId(&id);

  if (id != STM32_ID)
  {
    ESP_LOGE(Tag, "Invalid ID: %d", id);
  }
}

//_____________________________________________________________________________

static void ReadId(uint8_t* data)
{
  I2C_ReadFromAddress(SLAVE_ADDRESS, WHO_AM_I_REG_ADDRESS, data, 1u);
}
