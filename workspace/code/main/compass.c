static const char* Tag = "compass";

static T_Mag_Axis MagneticField;

//-----------------------------------------------------------------------------
// Private Functions Prototypes
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// Inline Code Definition
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
// Functions Implementation
//-----------------------------------------------------------------------------

void Compass_Init(void)
{
  LSM303C_InitMagnetometer();

  ESP_LOGI(Tag, "Compass is initialized");
}

//_____________________________________________________________________________

void Compass_GetMagneticField(void)
{
  LSM303C_GetMagneticField(&MagneticField);

  vmVariables.compass[0] = MagneticField.X;
  vmVariables.compass[1] = MagneticField.Y;
  vmVariables.compass[2] = MagneticField.Z;

  SET_EVENT(EVENT_COMPASS);
}
